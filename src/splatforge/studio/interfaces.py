"""Structural extension protocols; future representations need no core changes."""

from __future__ import annotations

from typing import Any, Protocol

import torch


class ReconstructionPipeline(Protocol):
    model: torch.nn.Module
    data: Any
    config: Any
    method: Any

    def parameter_groups(self) -> list[dict[str, Any]]: ...
    def parameters(self): ...
    def training_loss(self, sample, step: int): ...
    def after_backward(self, output): ...
    def after_step(self, step: int, optimizer): ...
    def update_learning_rates(self, step: int, optimizer): ...
    def statistics(self) -> dict[str, Any]: ...
    def state_dict(self) -> dict[str, Any]: ...
    def load_state_dict(self, state: dict[str, Any]): ...
    def save_representation(self, output) -> dict[str, Any]: ...
    def render(self, camera): ...


class MethodPlugin(Protocol):
    name: str
    description: str
    exporter: str
    requires_prior: bool

    @classmethod
    def default_config(cls): ...

    @classmethod
    def make_pipeline(cls, config) -> ReconstructionPipeline: ...


class MeshExporter(Protocol):
    def export(
        self, pipeline: ReconstructionPipeline, path, config
    ) -> dict[str, Any]: ...
